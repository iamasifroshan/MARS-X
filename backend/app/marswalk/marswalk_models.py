"""Pydantic data models for MARS-X Marswalk Route Generation — Phase 8.8.2.

Provides validated request/response models, point telemetry, summary metrics,
exposure breakdowns, and non-negotiable astronaut safety disclaimers.
"""

from typing import Optional, List, Dict, Any, Tuple
from pydantic import BaseModel, Field


# Mandatory non-negotiable safety disclaimer
MARSWALK_SAFETY_DISCLAIMER = (
    "Minimizing analytical terrain cost does not certify physical astronaut or rover safety. "
    "Microtopographic hazards below sensor resolution (boulders, fissures, loose dust depth), "
    "regolith bearing capacity, and mechanical slippage are not modeled in orbital DEMs. "
    "No route generated by MARS-X is certified safe for human or robotic traversal."
)


class MarswalkRouteRequest(BaseModel):
    """Request payload for terrain-aware Marswalk pathfinding."""
    start_lat: float = Field(..., ge=-90.0, le=90.0, description="Start latitude in planetocentric degrees")
    start_lon: float = Field(..., description="Start longitude in planetocentric degrees (0–360°E or -180–180°)")
    dest_lat: float = Field(..., ge=-90.0, le=90.0, description="Destination latitude in planetocentric degrees")
    dest_lon: float = Field(..., description="Destination longitude in planetocentric degrees (0–360°E or -180–180°)")
    preferred_source: Optional[str] = Field(
        default="auto",
        description="Preferred terrain source ('auto', 'hirise-holden', 'ctx-tyrrhena', 'ctx-apollinaris', 'mola-128ppd', 'mola-4ppd')",
    )
    slope_penalty_factor: float = Field(
        default=2.0,
        ge=0.0,
        le=20.0,
        description="Quadratic slope cost penalty multiplier beta >= 0",
    )
    max_slope_deg: float = Field(
        default=25.0,
        ge=5.0,
        le=85.0,
        description="Hard maximum passable slope cutoff in degrees",
    )
    max_search_nodes: int = Field(
        default=150000,
        ge=1000,
        le=1000000,
        description="Maximum A* node expansion limit before timeout",
    )
    algorithm: Optional[str] = Field(
        default="astar",
        description="Pathfinding algorithm: 'astar' (heuristic-guided) or 'dijkstra' (uniform-cost)",
    )
    route_name: Optional[str] = Field(
        default=None,
        description="Optional human-readable label for the planned traverse",
    )


class MarswalkRoutePoint(BaseModel):
    """Telemetry for a single sampled waypoint along the planned traverse."""
    index: int
    lat: float
    lon: float
    elevation_m: float
    slope_deg: float
    slope_category: str
    cumulative_distance_m: float


class MarswalkRouteResponse(BaseModel):
    """Full route generation response with geometry, telemetry, metrics and disclaimers."""
    route_id: str
    status: str
    route_name: Optional[str] = None
    start_coord: Tuple[float, float]
    dest_coord: Tuple[float, float]
    snapped_start_coord: Tuple[float, float]
    snapped_dest_coord: Tuple[float, float]
    source_dataset: str
    instrument: str
    tier: str
    native_resolution_m: float
    native_resolution_desc: str
    vertical_datum: str
    vertical_datum_type: str
    total_surface_distance_m: float
    total_horizontal_distance_m: float
    total_optimization_cost: float = Field(
        default=0.0,
        description="Total analytical graph traversal cost (minimized by A*/Dijkstra). Distinct from physical surface distance.",
    )
    cumulative_elevation_gain_m: float
    cumulative_elevation_loss_m: float
    min_elevation_m: float
    max_elevation_m: float
    max_route_slope_deg: float
    mean_route_slope_deg: float
    slope_band_exposure_pct: Dict[str, float]
    unknown_data_exposure_pct: float
    geometry: Dict[str, Any]  # GeoJSON LineString
    path_points: List[MarswalkRoutePoint]
    cost_function_parameters: Dict[str, Any]
    search_metrics: Dict[str, Any]
    coverage_limitations: str
    safety_disclaimer: str = MARSWALK_SAFETY_DISCLAIMER


class ValidatedCorridorPreset(BaseModel):
    """Curated validated Marswalk corridor for explorer demonstration."""
    corridor_id: str
    name: str
    region: str
    source_dataset: str
    start_lat: float
    start_lon: float
    dest_lat: float
    dest_lon: float
    description: str
    target_geology: str


class MarswalkMetadataResponse(BaseModel):
    """Metadata describing the Marswalk routing engine capabilities and constraints."""
    supported_datasets: List[Dict[str, Any]]
    resolution_tiers: List[Dict[str, Any]]
    slope_thresholds_deg: Dict[str, Any]
    default_parameters: Dict[str, Any]
    cost_function_definition: str
    heuristic_definition: str
    engine_versions: Optional[Dict[str, str]] = None
    safety_disclaimer: str = MARSWALK_SAFETY_DISCLAIMER
    validated_corridors: List[ValidatedCorridorPreset]
